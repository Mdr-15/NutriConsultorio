const {chromium}=require('playwright');const {spawn}=require('child_process');
const ROOT=require('path').resolve(__dirname,'..'),PORT=8115,B='http://localhost:'+PORT;
let fails=0;const ok=(n,c,x='')=>{console.log((c?'OK   ':'FAIL ')+n+(c?'':'  -> '+x));if(!c)fails++;};
(async()=>{
 const srv=spawn('node',[__dirname+'/mock.js',ROOT,String(PORT)],{stdio:'ignore'});await new Promise(r=>setTimeout(r,800));
 const br=await chromium.launch();const pg=await br.newPage({viewport:{width:1280,height:900}});const errs=[];pg.on('pageerror',e=>errs.push(e.message));pg.on('dialog',d=>d.accept());
 await pg.goto(B+'/');await pg.fill('#lu','admin');await pg.fill('#lp','clave-segura-123');await pg.click('#lb');await pg.waitForSelector('#login',{state:'hidden'});
 await pg.goto(B+'/#/expediente/PAC-0002');await pg.waitForSelector('.hub-tabs');
 ok('Cinco pestañas',(await pg.$$('.hub-tab')).length===5);
 await pg.click('.hub-tab[href$="/mediciones"]');await pg.waitForSelector('#medicionesForm');
 ok('URL con pestaña',/PAC-0002\/mediciones/.test(pg.url()));
 ok('Selector de paciente oculto',!(await pg.isVisible('#medicionesPatient')));
 await pg.fill('#medicionesForm [name=Peso_kg]','81.5');await pg.click('#medicionesForm button[type=submit]');await pg.waitForTimeout(1500);
 ok('Medición guardada aparece en lista',/81[.,]5/.test(await pg.textContent('#medicionesList')));
 ok('Formulario sigue visible (sin recarga)',await pg.isVisible('#medicionesForm'));
 await pg.click('.hub-tab[href$="/plan"]');await pg.waitForSelector('#planesForm');
 ok('Selector de plan oculto',!(await pg.isVisible('#planesPatient')));
 ok('Vista previa vacía al inicio',/Captura el objetivo/.test(await pg.textContent('#planPreview')));
 await pg.fill('#planesForm [name=Objetivo]','Bajar 3 kg');await pg.fill('#planesForm [name=Kcal]','1800');await pg.fill('#planesForm [name=Proteina_g]','100');await pg.fill('#planesForm [name=Desayuno]','Avena con fruta');await pg.click('.wk-box summary');await pg.fill('.wk-in[data-d=Lunes]','Pollo con verduras');
 const pv=await pg.textContent('#planPreview');
 ok('Vista previa refleja objetivo, kcal, comida y menú',/Bajar 3 kg/.test(pv)&&/1800/.test(pv)&&/Avena con fruta/.test(pv)&&/Pollo con verduras/.test(pv),pv.slice(0,200));
 ok('Vista previa con barra de macros',!!(await pg.$('#planPreview .macro-bar')));
 await pg.fill('#planesForm [name=Proteina_g]','');await pg.fill('#planesForm [name=Kcal]','1800');await pg.click('#planesForm button[type=submit]');await pg.waitForTimeout(1500);
 ok('Plan guardado en lista',/Bajar 3 kg/.test(await pg.textContent('#planesList')));
 await pg.click('.hub-tab[href$="/consultas"]');await pg.waitForTimeout(500);
 ok('Pestaña Consultas',await pg.isVisible('.hub-tab.on'));
 await pg.reload();await pg.waitForSelector('.hub-tabs');
 ok('Recarga conserva pestaña',/consultas/.test(pg.url())&&/Consultas/.test(await pg.textContent('.hub-tab.on')));
 ok('Sin errores JS',errs.length===0,errs.join('|'));
 await br.close();srv.kill();process.exit(fails?1:0);
})();
